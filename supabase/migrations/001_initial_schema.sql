-- Migrated from MySQL (assets/sql/database.sql) for Supabase PostgreSQL 15+
-- ============================================================================

-- Custom ENUM types mapped from MySQL ENUMs
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'parent_type_enum') THEN
        CREATE TYPE public.parent_type_enum AS ENUM ('Primary', 'Secondary');
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'cars_risk_status_enum') THEN
        CREATE TYPE public.cars_risk_status_enum AS ENUM ('NO-RISK', 'AT-RISK', 'HIGH-RISK', 'INCOMPLETE');
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'cars_tier_level_enum') THEN
        CREATE TYPE public.cars_tier_level_enum AS ENUM ('Tier 1', 'Tier 2', 'Tier 3', 'Pending');
    END IF;
END
$$;

-- ============================================================================
-- 1. Authorized Admins / Counselors (replaces legacy `admins` password table)
--    Authentication is handled by Supabase Auth (`auth.users`).
--    This table stores authorized counselor identities for RLS authorization.
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.admins (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    auth_user_id UUID UNIQUE REFERENCES auth.users(id) ON DELETE SET NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================================
-- 2. Grade Sections Lookup (replaces mutable `config/sections.json` on disk)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.grade_sections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_level VARCHAR(50) NOT NULL CHECK (
        grade_level IN (
            'Kindergarten',
            'Grade 1',
            'Grade 2',
            'Grade 3',
            'Grade 4',
            'Grade 5',
            'Grade 6'
        )
    ),
    section_name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_grade_sections_unique
    ON public.grade_sections (grade_level, lower(section_name));

-- ============================================================================
-- 3. Students (Learner Information)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.students (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(255) DEFAULT NULL,
    lrn VARCHAR(50) DEFAULT NULL,
    grade_section VARCHAR(100) DEFAULT NULL,
    grade_level VARCHAR(20) DEFAULT NULL,
    section VARCHAR(100) DEFAULT NULL,
    school_year VARCHAR(50) DEFAULT NULL,
    date_of_birth DATE DEFAULT NULL,
    contact_number VARCHAR(50) DEFAULT NULL,
    home_address TEXT DEFAULT NULL,
    blood_type VARCHAR(10) DEFAULT NULL,
    allergies TEXT DEFAULT NULL,
    medications TEXT DEFAULT NULL,
    status VARCHAR(50) DEFAULT 'Unknown / Not Indicated',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_students_deleted_at ON public.students (deleted_at);
CREATE INDEX IF NOT EXISTS idx_students_grade_section_status ON public.students (grade_level, section, status) WHERE deleted_at IS NULL;
CREATE INDEX IF NOT EXISTS idx_students_lrn ON public.students (lrn);

-- ============================================================================
-- 4. Parents / Guardians
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.parents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    parent_type public.parent_type_enum NOT NULL,
    full_name VARCHAR(255) DEFAULT NULL,
    relationship VARCHAR(100) DEFAULT NULL,
    home_address TEXT DEFAULT NULL,
    mobile_number VARCHAR(50) DEFAULT NULL,
    telephone_number VARCHAR(50) DEFAULT NULL,
    email_address VARCHAR(255) DEFAULT NULL,
    workplace VARCHAR(255) DEFAULT NULL,
    workplace_address TEXT DEFAULT NULL,
    emergency_contact_number VARCHAR(50) DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_parents_student_id ON public.parents (student_id);
CREATE INDEX IF NOT EXISTS idx_parents_deleted_at ON public.parents (deleted_at);

-- ============================================================================
-- 5. Guidance Office Assessment Records
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.assessment_records (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    record_number VARCHAR(50) UNIQUE DEFAULT NULL,
    school_year VARCHAR(20) DEFAULT NULL,
    date DATE DEFAULT NULL,
    grade_section VARCHAR(100) DEFAULT NULL,
    contact_number VARCHAR(50) DEFAULT NULL,
    status VARCHAR(50) DEFAULT NULL,
    assessment_provider VARCHAR(100) DEFAULT NULL,
    findings TEXT DEFAULT NULL,
    diagnosis VARCHAR(100) DEFAULT NULL,
    recommendations TEXT DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_assessment_records_student_id ON public.assessment_records (student_id);
CREATE INDEX IF NOT EXISTS idx_assessment_records_deleted_at ON public.assessment_records (deleted_at);

-- ============================================================================
-- 6. Guidance Office Case Register
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.case_register (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_number VARCHAR(50) UNIQUE DEFAULT NULL,
    school_year VARCHAR(20) DEFAULT NULL,
    date DATE DEFAULT NULL,
    grade_section VARCHAR(100) DEFAULT NULL,
    case_type VARCHAR(100) DEFAULT NULL,
    brief_description TEXT DEFAULT NULL,
    actions_taken TEXT DEFAULT NULL,
    outcome_disposition VARCHAR(50) DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ DEFAULT NULL
);

CREATE INDEX IF NOT EXISTS idx_case_register_deleted_at ON public.case_register (deleted_at);

-- ============================================================================
-- 7. Case-Students Junction (Many-to-Many)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.case_students (
    case_id BIGINT NOT NULL REFERENCES public.case_register(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    PRIMARY KEY (case_id, student_id)
);

CREATE INDEX IF NOT EXISTS idx_case_students_student_id ON public.case_students (student_id);

-- ============================================================================
-- 8. CARS Module Tables (Preserved from assets/sql/database.sql for zero data loss)
-- ============================================================================
CREATE TABLE IF NOT EXISTS public.cars_assessment_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year VARCHAR(50) DEFAULT NULL,
    grade_level VARCHAR(50) DEFAULT NULL,
    section_name VARCHAR(100) DEFAULT NULL,
    evaluator_id BIGINT DEFAULT NULL,
    assessed_at DATE DEFAULT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.cars_student_evaluations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES public.cars_assessment_sessions(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
    q1 SMALLINT DEFAULT NULL, q2 SMALLINT DEFAULT NULL, q3 SMALLINT DEFAULT NULL, q4 SMALLINT DEFAULT NULL,
    q5 SMALLINT DEFAULT NULL, q6 SMALLINT DEFAULT NULL, q7 SMALLINT DEFAULT NULL, q8 SMALLINT DEFAULT NULL,
    q9 SMALLINT DEFAULT NULL, q10 SMALLINT DEFAULT NULL, q11 SMALLINT DEFAULT NULL, q12 SMALLINT DEFAULT NULL,
    q13 SMALLINT DEFAULT NULL, q14 SMALLINT DEFAULT NULL, q15 SMALLINT DEFAULT NULL, q16 SMALLINT DEFAULT NULL,
    q17 SMALLINT DEFAULT NULL, q18 SMALLINT DEFAULT NULL, q19 SMALLINT DEFAULT NULL, q20 SMALLINT DEFAULT NULL,
    q21 SMALLINT DEFAULT NULL, q22 SMALLINT DEFAULT NULL, q23 SMALLINT DEFAULT NULL, q24 SMALLINT DEFAULT NULL,
    externalizing_score INTEGER DEFAULT NULL,
    internalizing_score INTEGER DEFAULT NULL,
    social_score INTEGER DEFAULT NULL,
    academic_score INTEGER DEFAULT NULL,
    total_raw_score INTEGER DEFAULT NULL,
    t_score INTEGER DEFAULT NULL,
    percentile_rank INTEGER DEFAULT NULL,
    risk_status public.cars_risk_status_enum NOT NULL DEFAULT 'INCOMPLETE',
    tier_level public.cars_tier_level_enum NOT NULL DEFAULT 'Pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_cars_evaluations_session_id ON public.cars_student_evaluations (session_id);
CREATE INDEX IF NOT EXISTS idx_cars_evaluations_student_id ON public.cars_student_evaluations (student_id);

CREATE TABLE IF NOT EXISTS public.cars_norm_tables (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade_group VARCHAR(100) NOT NULL,
    raw_score INTEGER NOT NULL,
    t_score INTEGER NOT NULL,
    percentile INTEGER NOT NULL,
    CONSTRAINT idx_grade_raw UNIQUE (grade_group, raw_score)
);

